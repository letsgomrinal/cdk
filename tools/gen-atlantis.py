#!/usr/bin/env python3
"""Generate atlantis.yaml from every unit.yaml under a repo root.

Atlantis reads one atlantis.yaml at the repo root, so units can't each carry
their own. This script builds it from the units instead. A micro repo produces
a single-unit file and a monorepo produces one entry per unit. Same script,
same output format.

    tools/gen-atlantis.py [repo_root] > atlantis.yaml
    tools/gen-atlantis.py --check [repo_root]   # CI: fail if atlantis.yaml is stale

No third-party dependencies (unit.yaml is read with a minimal parser).
"""
import os
import re
import sys

SKIP_DIRS = {".git", ".terraform", "node_modules", "templates"}


def parse_unit(path):
    """Read the flat keys we need (product, envs) without needing PyYAML."""
    data = {}
    with open(path) as f:
        for line in f:
            line = line.split("#", 1)[0].rstrip()
            m = re.match(r"^(\w+):\s*(.*)$", line)
            if not m:
                continue
            key, val = m.groups()
            if val.startswith("[") and val.endswith("]"):
                data[key] = [v.strip() for v in val[1:-1].split(",") if v.strip()]
            else:
                data[key] = val.strip().strip('"\'')
    return data


def find_units(root):
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames[:] = sorted(d for d in dirnames if d not in SKIP_DIRS and not d.startswith(".terraform"))
        if "unit.yaml" in filenames:
            yield dirpath


def render(root):
    projects = []
    seen = set()
    for unit_dir in find_units(root):
        unit = parse_unit(os.path.join(unit_dir, "unit.yaml"))
        product = unit.get("product")
        if not product or not re.match(r"^[a-z][a-z0-9]{1,9}$", product):
            sys.exit(f"{unit_dir}/unit.yaml: invalid or missing product")
        deploy = os.path.relpath(os.path.join(unit_dir, "deploy"), root)
        for env in unit.get("envs", []):
            for f in (f"{env}.tfvars", f"{env}.backend.hcl"):
                if not os.path.exists(os.path.join(root, deploy, "env", f)):
                    sys.exit(f"{deploy}/env/{f} missing (listed in {unit_dir}/unit.yaml envs)")
            name = f"{product}-{env}"
            if name in seen:
                sys.exit(f"duplicate Atlantis project {name}: product codes must be unique")
            seen.add(name)
            projects.append((name, deploy, env))

    out = [
        "# GENERATED by tools/gen-atlantis.py from unit.yaml files. Do not edit.",
        "version: 3",
        "automerge: false",
        "parallel_plan: true",
        "parallel_apply: false",
        "projects:",
    ]
    for name, deploy, env in projects:
        out += [
            f"  - name: {name}",
            f"    dir: {deploy}",
            f"    workspace: {env}",
            "    workflow: cdk",
            "    autoplan:",
            "      enabled: true",
            f'      when_modified: ["*.tf", "env/{env}.*", "../unit.yaml"]',
        ]
    return "\n".join(out) + "\n"


def main():
    args = sys.argv[1:]
    check = "--check" in args
    args = [a for a in args if a != "--check"]
    root = args[0] if args else "."
    content = render(root)
    if check:
        target = os.path.join(root, "atlantis.yaml")
        current = open(target).read() if os.path.exists(target) else ""
        if current != content:
            sys.exit("atlantis.yaml is out of date: run tools/gen-atlantis.py > atlantis.yaml")
        return
    sys.stdout.write(content)


if __name__ == "__main__":
    main()
